    private void cargarCategorias() {
      File archivo = new File("electronica.csv"); 
        try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
            String linea;
            ComBoxCategorias.removeAllItems(); 
            
            // ELEMENTO VACÍO: Para obligar a elegir una categoría real
            ComBoxCategorias.addItem("- Seleccione una categoría -"); 
            
            while ((linea = br.readLine()) != null) {
                String[] datos = linea.split(",");
                if (datos.length >= 2) {
                    String codigo = datos[0].trim();
                    String nombre = datos[1].trim();
                    ComBoxCategorias.addItem(nombre); 
                    mapaCategorias.put(nombre, codigo); 
                }
            }
            ComBoxCategorias.setSelectedIndex(0);
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error: No se encontró electronica.csv");
        }
    }
    
