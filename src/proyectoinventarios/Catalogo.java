    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
      // 1. VALIDACIÓN GLOBAL (Si nada ha sido llenado)
        if (txtClave.getText().trim().isEmpty() && txtNombre.getText().trim().isEmpty() && 
            ComBoxCategorias.getSelectedIndex() == 0) {
            
            JOptionPane.showMessageDialog(this, "DEBE LLENAR LOS CAMPOS para poder registrar.");
            txtClave.requestFocus();
            return;
        }

        // 2. VALIDACIONES INDIVIDUALES PERSONALIZADAS
        if (txtClave.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, ingresa la CLAVE.");
            txtClave.requestFocus();
            return;
        }
        if (txtNombre.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "El campo NOMBRE está vacío.");
            txtNombre.requestFocus();
            return;
        }
        if (ComBoxCategorias.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Selecciona una CATEGORÍA válida.");
            ComBoxCategorias.requestFocus();
            return;
        }
        if (txtStockA.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Falta el STOCK ACTUAL.");
            txtStockA.requestFocus();
            return;
        }
        if (txtStockM.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Falta el STOCK MÍNIMO.");
            txtStockM.requestFocus();
            return;
        }
        if (txtPrecio.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingresa el PRECIO.");
            txtPrecio.requestFocus();
            return;
        }
        if (txtCosto.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingresa el COSTO.");
            txtCosto.requestFocus();
            return;
        }
        if (txtEntrega.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Falta el TIEMPO DE ENTREGA.");
            txtEntrega.requestFocus();
            return;
        }
        if (txtDemanda.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingresa la DEMANDA actual.");
            txtDemanda.requestFocus();
            return;
        }

        // 3. VERIFICAR SI LA CLAVE YA EXISTE (Para que no haya duplicados)
        if (existeClave(txtClave.getText().trim())) {
            JOptionPane.showMessageDialog(this, "Esa CLAVE ya existe. Usa una diferente.");
            txtClave.requestFocus();
            return;
        }

        // 4. CREACIÓN Y ESCRITURA OBLIGATORIA DEL ARCHIVO
        try {
            // El 'true' asegura que se agregue al final sin borrar lo anterior
            FileWriter fw = new FileWriter(ARCHIVO_PRODUCTOS, true);
            PrintWriter pw = new PrintWriter(fw);

            String nombreCat = ComboBoxCategorias.getSelectedItem().toString();
            String codigoCat = mapaCategorias.get(nombreCat);
            String categoriaFinal = codigoCat + " - " + nombreCat;

            // Guardamos con tus nombres de variables
            pw.println(txtClave.getText().trim() + "," + 
                       txtNombre.getText().trim() + "," + 
                       categoriaFinal + "," + 
                       txtStockA.getText().trim() + "," + 
                       txtStockM.getText().trim() + "," + 
                       txtPrecio.getText().trim() + "," + 
                       txtCosto.getText().trim() + "," + 
                       txtEntrega.getText().trim() + "," + 
                       txtDemanda.getText().trim() + ",true");
            
            pw.close(); 

            JOptionPane.showMessageDialog(this, "¡Producto registrado y guardado en " + ARCHIVO_PRODUCTOS + "!");
            limpiarCampos();
            txtClave.requestFocus();

        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error fatal al crear el archivo.");
        }
    }                                          

    // Método para leer el archivo y buscar si la clave ya está
    private boolean existeClave(String claveABuscar) {
        File archivo = new File(ARCHIVO_PRODUCTOS);
        if (!archivo.exists()) return false; 

        try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
            String linea;
            while ((linea = br.readLine()) != null) {
                String[] datos = linea.split(",");
                if (datos.length > 0 && datos[0].equals(claveABuscar)) {
                    return true; 
                }
            }
        } catch (IOException e) {
            System.err.println("Error al validar clave.");
        }
        return false;
    }//GEN-LAST:event_btnRegistrarActionPerformed

